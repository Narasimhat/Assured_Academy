import {test,expect} from '@playwright/test';
import path from 'node:path';
import fs from 'node:fs';
const reference=path.resolve('public/examples/apoe-reference.gb');
test('a newcomer can design, select a pair, export, restore, and retain provenance',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));await page.goto('/');
 await expect(page.getByRole('heading',{name:'Big questions. Small, precise changes.'})).toBeVisible();
 await page.screenshot({path:'test-results/studio-overview.png',fullPage:true});
 await page.getByRole('button',{name:'Design an edit',exact:true}).click();
 await page.getByLabel('Gene symbol').fill('APOE');await page.getByLabel('Amino-acid change').fill('R176C');await page.getByLabel('Cell line',{exact:true}).fill('BIHi005-a');
 await page.locator('input[type=file][accept=".gb,.gbk,.gbff,.genbank"]').setInputFiles(reference);
 await page.getByRole('button',{name:'Explore design',exact:true}).click();
 await expect(page.getByRole('heading',{name:'APOE · R176C'})).toBeVisible();
 await expect(page.getByText('NM_000041.4',{exact:false})).toBeVisible();
 await expect(page.getByText('Review required',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:/Alternative 2/}).click();
 await expect(page.getByRole('button',{name:/Alternative 2/})).toHaveAttribute('aria-pressed','true');
 await page.screenshot({path:'test-results/studio-design.png',fullPage:true});
 const [specDownload]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Export QC design',exact:false}).click()]);
 const spec=JSON.parse(fs.readFileSync(await specDownload.path(),'utf8'));expect(spec.guides).toHaveLength(1);expect(spec.donors).toHaveLength(1);expect(spec.guides[0].spacer).toBe('CCCCGGCCTGGTACACTGCC');
 const [bundleDownload]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Save project',exact:true}).click()]);const bundle=await bundleDownload.path();
 await page.reload();await page.getByRole('button',{name:'Review design',exact:true}).click();await expect(page.getByRole('button',{name:/Alternative 2/})).toHaveAttribute('aria-pressed','true');
 page.on('dialog',d=>d.accept());await page.locator('input[type=file][accept=".zip"]').setInputFiles(bundle);
 await expect(page.getByRole('heading',{name:'Let the evidence speak.'})).toBeVisible();
 await expect(page.getByText('Connected to your selected experimental alternative')).toBeVisible();
 expect(errors).toEqual([]);
});
test('simulated QC requires confirmed controls, retains partial outcomes, exports and reloads',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));await page.goto('/');await page.getByRole('button',{name:'Check sequencing reads',exact:true}).click();
 await page.getByRole('button',{name:/Try the simulated QC example/}).click();
 await expect(page.getByRole('button',{name:'Analyze reads',exact:true})).toBeDisabled();
 for(let i=1;i<=3;i++)await page.getByLabel(`Confirm pairing ${i}`,{exact:true}).check();
 await page.getByRole('button',{name:'Analyze reads',exact:true}).click();
 await expect(page.getByRole('heading',{name:'A clearer view of your clones.'})).toBeVisible();
 await expect(page.locator('.results-table tbody tr')).toHaveCount(3);
 await expect(page.locator('.results-table tbody tr').first()).toContainText('accept');
 await expect(page.locator('.results-table tbody tr').nth(2)).not.toContainText('accept');
 await page.screenshot({path:'test-results/studio-results.png',fullPage:true});
 await expect(page.locator('.chromatogram img')).toBeVisible();
 const [report]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Download report',exact:true}).click()]);
 expect(fs.readFileSync(await report.path(),'utf8')).toContain('specHash');
 const [bundleDownload]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Save project',exact:true}).click()]);const bundle=await bundleDownload.path();
 await page.reload();await page.getByRole('button',{name:'Results',exact:false}).first().click();await expect(page.locator('.results-table tbody tr')).toHaveCount(3);
 page.on('dialog',d=>d.accept());await page.locator('input[type=file][accept=".zip"]').setInputFiles(bundle);
 await expect(page.locator('.results-table tbody tr')).toHaveCount(3);
 await page.getByRole('button',{name:'Check reads',exact:true}).click();await expect(page.locator('.file-list>div')).toHaveCount(4);
 await page.getByLabel('Control for sample 1',{exact:true}).selectOption('APOE_A01.ab1');
 await expect(page.getByRole('button',{name:'Analyze reads',exact:true})).toBeDisabled();
 await page.getByRole('button',{name:'Results',exact:false}).first().click();await expect(page.getByRole('heading',{name:'Your results will live here.'})).toBeVisible();
 expect(errors).toEqual([]);
});
test('mobile layout and keyboard entry remain usable',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/');
 await expect(page.getByRole('heading',{name:'Big questions. Small, precise changes.'})).toBeVisible();
 await page.getByRole('link',{name:'Skip to workspace',exact:true}).focus();await page.keyboard.press('Enter');await expect(page.locator('#main')).toBeFocused();
 await page.getByRole('button',{name:'Untitled exploration',exact:true}).click();await expect(page.getByRole('dialog')).toBeVisible();await page.keyboard.press('Escape');await expect(page.getByRole('dialog')).not.toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.screenshot({path:'test-results/studio-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'Design an edit',exact:true}).click();
 await expect(page.getByLabel('Gene symbol')).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.getByRole('button',{name:'New project',exact:false}).click();
 await page.getByLabel('Gene symbol').fill('APOE');await page.getByLabel('Amino-acid change').fill('R176C');
 await page.getByRole('button',{name:'Find in NCBI',exact:true}).click();
 await expect(page.getByLabel('Choose a versioned genomic reference')).toBeVisible({timeout:35000});
});
